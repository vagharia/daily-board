# letters, not ، ؛ ؟ or digits; written as regex escapes so that normalising a pattern (R) can't alter the class
_L = r"\u0621-\u063A\u0641-\u065F\u066E-\u06D3\u06D5\u06EE\u06EF\u06FA-\u06FF"
_B = f"(?<![{_L}])"              # no Persian letter just before
_E = f"(?![{_L}])"               # no Persian letter just after


def _lit(t):
    return re.escape(fa_norm(t)).replace(r"\ ", r"\s*")


def F(*terms, whole=False):
    """Persian alternatives as a regex: each term must start a word; with whole=True it must end one too."""
    return _B + "(?:" + "|".join(_lit(t) for t in terms) + ")" + (_E if whole else "")


def R(*parts):
    """A raw regex whose Persian literals are normalised like the text."""
    return "".join(fa_norm(p) if not p.startswith("re:") else p[3:] for p in parts)


def P(rx, base, topics=(), flags=()):
    return re.compile(rx), base, set(topics), set(flags)


