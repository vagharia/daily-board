def _quote(t):
    """'عراقچی: …' — a statement whose words may mention attacks without reporting one."""
    m = _QUOTE.match(t or "")
    return bool(m) and not _NOT_SPEAKER.search(m.group(1))


def score_fa(title: str, summary: str):
    """(severity, topics, flags) for a Persian headline and text."""
    t, s = fa_norm(to_latin_digits(title or "")), fa_norm(to_latin_digits(summary or ""))
    best, topics, flags, kinetic_in_title, title_best = 0.0, set(), set(), False, 0.0
    for rx, base, tp, fl in PATTERNS:
        if rx.search(t):
            val = base
            title_best = max(title_best, base)
            if base >= KINETIC_BASE:
                kinetic_in_title = True
        elif s and rx.search(s):
            val = base * (0.78 if base >= KINETIC_BASE else 0.9)
        else:
            continue
        topics |= tp
        flags |= fl
        best = max(best, val)
    if best == 0:
        best = 22.0
    strong = bool(STRONG.search(t))
    if DEESCALATE.search(t) and "threat" in flags:
        best = min(best, 45)
        flags.discard("threat")
    if DENIAL.search(t) and best >= 45:
        best *= 0.65
        flags.add("denial")
        flags -= HARD_EVENTS
    if kinetic_in_title and SPEC.search(t) and "kinetic_threat" not in flags and not strong:
        best *= 0.82
        flags.add("speculative")
    past = bool(PAST.search(t) or PAST.search(s[:160]))
    if past:
        best *= 0.6
        flags.add("past")
    if ACTOR.search(t) and flags & {"ultimatum", "kinetic_threat"}:
        best += 6
    elif ACTOR.search(t) and flags & {"threat", "retaliation"}:
        best = max(best, min(best + 6, 68))      # a leader's threat is serious, but not a strike
    if TARGET.search(t) and flags & {"kinetic", "maritime_incident"}:
        best += 6
    m = None if past else CASUALTIES.search(t + " " + s[:200])
    if m:
        n = int(m.group(1))
        best += 10 if n >= 50 else 6 if n >= 10 else 0
    if CONTROLLED.search(t) or CONTROLLED.search(s[:200]):
        best = min(best, 40)
        flags -= HARD_EVENTS
        flags.add("controlled")
    if FACTCHECK.search(t):
        best = min(best, 38)
        flags -= HARD_EVENTS
        flags.add("denial")
    lead = t + " " + s[:300]
    if (ATTACK_WORD.search(t) and VERBAL.search(lead) and not CONCRETE.search(lead)) or \
            (VERBAL_TARGET.search(t) and not CONCRETE.search(t)):
        best = min(best, 40)
        flags -= HARD_EVENTS
        flags.add("verbal")
    if title_best < 45:
        # nothing notable in the headline: a Persian lead paragraph mentions a lot, so it alone can't make a
        # report orange or an event
        best = min(best, 44)
        flags -= HARD_EVENTS
    if MEDIA_CITE.search(t) and not strong:
        best = min(best, 56)
        flags.add("analysis")
    if flags & HARD_EVENTS and not strong and (HYPO.search(t) or _quote(t)):
        best = min(best, 66 if HYPO.search(t) else 64)   # "تهدید به حمله", "طرح حمله", "X: …حمله…"
        flags -= HARD_EVENTS
        flags |= {"speculative", "threat"} if HYPO.search(t) else {"quote"}
    if REACTION.search(t):
        best = min(best, 54)                       # reactions to an event rank below the event itself
        flags.add("reaction")
        flags.discard("kinetic")
    if QUESTION.search(t):
        best = min(best, 56)
        flags.add("speculative")
    if OPINION.search(t):
        best = min(best, 38)
        flags.add("opinion")
    elif ANALYSIS.search(t) and not LIVE.search(t):
        best = min(best, 44)
        flags.add("analysis")
    return max(5.0, min(98.0, best)), topics, flags
